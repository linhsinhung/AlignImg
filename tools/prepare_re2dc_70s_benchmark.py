#!/usr/bin/env python3
"""Build the complete reproducible, phase-corrected 70S benchmark stack."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import math
from pathlib import Path
from typing import Any

import mrcfile
import numpy as np


DEFAULT_STAR = Path("data/re2dc_70s_testdata/70s_rib_real.star")
DEFAULT_OUTPUT = Path("data/re2dc_70s_testdata/prepared/re2dc_70s_n5000_s128")
DEFAULT_PARTICLE_COUNT = 5000
DEFAULT_PIXEL_SIZE_ANGSTROM = 2.82


def read_particle_loop(path: Path) -> tuple[list[str], list[list[str]]]:
    """Read the particle/image loop from a RELION STAR file."""
    lines = path.read_text(encoding="utf-8").splitlines()
    in_particles = False
    labels: list[str] = []
    rows: list[list[str]] = []
    reading_rows = False
    for line in lines:
        value = line.strip()
        if value.startswith("data_"):
            if in_particles and rows:
                break
            in_particles = value in {"data_particles", "data_images"}
            labels = [] if in_particles else labels
            reading_rows = False
            continue
        if not in_particles or not value or value.startswith("#"):
            continue
        if value == "loop_":
            continue
        if value.startswith("_rln"):
            labels.append(value.split()[0])
            continue
        if labels:
            reading_rows = True
        if reading_rows:
            fields = value.split()
            if len(fields) != len(labels):
                raise ValueError(
                    f"STAR row has {len(fields)} fields but {len(labels)} labels: {value}"
                )
            rows.append(fields)
    if not labels or not rows:
        raise ValueError(f"no data_particles/data_images loop found in {path}")
    return labels, rows


def electron_wavelength(voltage_kv: float) -> float:
    voltage = voltage_kv * 1000.0
    return 12.398 / math.sqrt(voltage * (1.0 + voltage * 0.978e-6))


def ctf_array(
    shape: tuple[int, int],
    *,
    pixel_size: float,
    defocus_u: float,
    defocus_v: float,
    defocus_angle_deg: float,
    voltage_kv: float,
    cs_mm: float,
    amplitude_contrast: float,
    phase_shift_deg: float = 0.0,
) -> np.ndarray:
    """Return an unshifted real-valued CTF using the supplied RE2DC convention."""
    fy = np.fft.fftfreq(shape[0], d=pixel_size)
    fx = np.fft.fftfreq(shape[1], d=pixel_size)
    fx, fy = np.meshgrid(fx, fy)
    squared_frequency = fx * fx + fy * fy
    direction = np.arctan2(fy, fx)
    astigmatism_angle = np.deg2rad(defocus_angle_deg)
    defocus = 0.5 * (defocus_u + defocus_v) + 0.5 * (
        defocus_u - defocus_v
    ) * np.cos(2.0 * (direction - astigmatism_angle))
    wavelength = electron_wavelength(voltage_kv)
    gamma = (
        np.pi * wavelength * defocus * squared_frequency
        - 0.5
        * np.pi
        * cs_mm
        * 1.0e7
        * wavelength**3
        * squared_frequency**2
        + np.deg2rad(phase_shift_deg)
    )
    return -(
        np.sqrt(1.0 - amplitude_contrast**2) * np.sin(gamma)
        + amplitude_contrast * np.cos(gamma)
    )


def phase_flip(image: np.ndarray, ctf: np.ndarray) -> np.ndarray:
    """Correct CTF phase reversals without amplifying frequencies near CTF zeros."""
    sign = np.sign(ctf)
    sign[sign == 0.0] = 1.0
    corrected = np.fft.ifft2(np.fft.fft2(image) * sign).real
    polarity = -1.0 if float(np.sum(ctf)) < 0.0 else 1.0
    return np.asarray(corrected * polarity, dtype=np.float32)


def fourier_crop(image: np.ndarray, size: int) -> np.ndarray:
    """Fourier-crop a square image while preserving a constant image's amplitude."""
    old_size = int(image.shape[0])
    if image.shape != (old_size, old_size):
        raise ValueError(f"expected a square image, got {image.shape}")
    if size > old_size or size < 1:
        raise ValueError(f"output size must be in 1..{old_size}")
    if size % 2:
        raise ValueError("prepared alignment stacks require an even output size")
    if size == old_size:
        return np.asarray(image, dtype=np.float32)
    start = (old_size - size) // 2
    stop = start + size
    spectrum = np.fft.fftshift(np.fft.fft2(image))[start:stop, start:stop]
    cropped = np.fft.ifft2(np.fft.ifftshift(spectrum)).real
    cropped *= (size / old_size) ** 2
    return np.asarray(cropped, dtype=np.float32)


def write_star(
    path: Path,
    labels: list[str],
    selected_rows: list[list[str]],
    stack_name: str,
) -> None:
    image_column = labels.index("_rlnImageName")
    lines = [
        "# Generated by tools/prepare_re2dc_70s_benchmark.py",
        "# Images are CTF phase-corrected; do not apply CTF correction again.",
        "",
        "data_images",
        "",
        "loop_",
    ]
    lines.extend(f"{label} #{index + 1}" for index, label in enumerate(labels))
    for output_index, source_row in enumerate(selected_rows, start=1):
        row = list(source_row)
        row[image_column] = f"{output_index:06d}@{stack_name}"
        lines.append(" ".join(row))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def jsonable(value: Any) -> Any:
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, Path):
        return str(value)
    raise TypeError(f"cannot serialize {type(value).__name__}")


def build(args: argparse.Namespace) -> dict[str, Any]:
    star_path = args.star.resolve()
    labels, rows = read_particle_loop(star_path)
    columns = {label: index for index, label in enumerate(labels)}
    required = (
        "_rlnImageName",
        "_rlnDefocusU",
        "_rlnDefocusV",
        "_rlnDefocusAngle",
        "_rlnAmplitudeContrast",
        "_rlnSphericalAberration",
        "_rlnVoltage",
    )
    missing = [label for label in required if label not in columns]
    if missing:
        raise ValueError(f"STAR is missing required CTF fields: {missing}")
    enabled_column = columns.get("_rlnEnabled")
    eligible = np.asarray(
        [
            index
            for index, row in enumerate(rows)
            if enabled_column is None or int(float(row[enabled_column])) == 1
        ],
        dtype=np.int64,
    )
    if args.count > len(eligible):
        raise ValueError(f"requested {args.count} particles but only {len(eligible)} are enabled")
    if args.count == len(eligible):
        selected = eligible.copy()
        selection = {"method": "all_enabled_in_source_order"}
    else:
        rng = np.random.default_rng(args.seed)
        selected = np.sort(rng.choice(eligible, size=args.count, replace=False))
        selection = {"method": "seeded_random_without_replacement", "seed": args.seed}
    selected_rows = [rows[int(index)] for index in selected]

    stack_specs: dict[Path, list[tuple[int, int]]] = {}
    image_column = columns["_rlnImageName"]
    for output_index, row in enumerate(selected_rows):
        image_index, relative_path = row[image_column].split("@", maxsplit=1)
        stack_path = Path(relative_path)
        if not stack_path.is_absolute():
            stack_path = star_path.parent / stack_path
        stack_specs.setdefault(stack_path.resolve(), []).append(
            (output_index, int(image_index) - 1)
        )

    output = np.empty((args.count, args.size, args.size), dtype=np.float32)
    source_shape: tuple[int, int] | None = None
    for stack_path, requests in stack_specs.items():
        with mrcfile.mmap(stack_path, permissive=True, mode="r") as mrc:
            stack = mrc.data
            for output_index, image_index in requests:
                image = np.asarray(stack[image_index], dtype=np.float32)
                if source_shape is None:
                    source_shape = tuple(image.shape)
                elif tuple(image.shape) != source_shape:
                    raise ValueError("all source particles must have the same shape")
                row = selected_rows[output_index]
                ctf = ctf_array(
                    tuple(image.shape),
                    pixel_size=args.pixel_size,
                    defocus_u=float(row[columns["_rlnDefocusU"]]),
                    defocus_v=float(row[columns["_rlnDefocusV"]]),
                    defocus_angle_deg=float(row[columns["_rlnDefocusAngle"]]),
                    voltage_kv=float(row[columns["_rlnVoltage"]]),
                    cs_mm=float(row[columns["_rlnSphericalAberration"]]),
                    amplitude_contrast=float(row[columns["_rlnAmplitudeContrast"]]),
                    phase_shift_deg=(
                        float(row[columns["_rlnPhaseShift"]])
                        if "_rlnPhaseShift" in columns
                        else 0.0
                    ),
                )
                output[output_index] = fourier_crop(
                    phase_flip(image, ctf), args.size
                )

    assert source_shape is not None
    output_pixel_size = args.pixel_size * source_shape[0] / args.size
    args.output.parent.mkdir(parents=True, exist_ok=True)
    stack_path = args.output.with_suffix(".mrcs")
    subset_star_path = args.output.with_suffix(".star")
    manifest_path = args.output.with_suffix(".json")
    with mrcfile.new(stack_path, overwrite=True) as mrc:
        mrc.set_data(output)
        mrc.voxel_size = output_pixel_size
        mrc.update_header_stats()
    write_star(subset_star_path, labels, selected_rows, stack_path.name)
    manifest = {
        "schema": "alignimg.re2dc-70s-prepared.v1",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "source_star": str(star_path),
        "source_stacks": [str(path) for path in stack_specs],
        "source_particle_count": len(rows),
        "selected_source_row_indices_zero_based": selected,
        "selection": selection,
        "particle_count": args.count,
        "source_shape": list(source_shape),
        "output_shape": list(output.shape[1:]),
        "input_pixel_size_angstrom": args.pixel_size,
        "output_pixel_size_angstrom": output_pixel_size,
        "ctf_preprocessing": {
            "mode": "phase_flip",
            "description": (
                "Corrects CTF phase reversals using sign(CTF). It intentionally does "
                "not invert the CTF amplitude near zeros. Alignment must not apply CTF "
                "correction a second time."
            ),
            "ctf_convention_source": "data/re2dc_70s_testdata/toolbox_preprocess/ctf_tool.py",
            "phase_shift_source": (
                "_rlnPhaseShift" if "_rlnPhaseShift" in columns else "constant_0_degrees"
            ),
            "performed_before_fourier_crop": True,
        },
        "resampling": {
            "method": "centered_fourier_crop",
            "source_size": source_shape[0],
            "output_size": args.size,
        },
        "outputs": {"stack": str(stack_path), "star": str(subset_star_path)},
        "value_statistics": {
            "minimum": float(np.min(output)),
            "maximum": float(np.max(output)),
            "mean": float(np.mean(output)),
            "standard_deviation": float(np.std(output)),
        },
    }
    manifest_path.write_text(
        json.dumps(manifest, default=jsonable, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return manifest


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--star", type=Path, default=DEFAULT_STAR)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--count", type=int, default=DEFAULT_PARTICLE_COUNT)
    parser.add_argument("--size", type=int, default=128)
    parser.add_argument("--pixel-size", type=float, default=DEFAULT_PIXEL_SIZE_ANGSTROM)
    parser.add_argument("--seed", type=int, default=0)
    return parser.parse_args()


if __name__ == "__main__":
    result = build(parse_args())
    print(json.dumps(result["outputs"], indent=2))
